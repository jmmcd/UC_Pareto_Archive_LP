"""Payoff table: the ranges used to normalise the objectives.

For each solar size, minimise each of the four objectives on its own
(run.payoff_table does the solves).  Row k of the payoff table holds
all four objective values at the solution that minimises objective k
alone.  Then

    min (ideal)          the diagonal: each objective at its own best
    max (nadir estimate) the column-wise worst: the largest value an
                         objective takes when any one of the other
                         objectives is minimised alone

and range = max - min is the scale the "_norm" runs divide each weight
by.  This is the standard nadir estimate for more than two objectives;
it is not guaranteed to be the true nadir of the Pareto front.

Usage:
    python payoff.py      # writes ../paper/tables/payoff_table.tex
                          # and ../derived/payoff_table.csv
"""

import os
import sys

import numpy as np
import pandas as pd


SOLAR_SIZES = (0, 10, 50, 100)
OBJECTIVES = ["technology_cost", "emissions", "env_cost", "sus_cost"]
LABELS = ["Prod cost", "Emissions", "Env cost", "Sus cost"]

TABDIR = "../paper/tables/"
DERIVED = "../derived/"


def reload_run(solar_size, scenario="base"):
    """Import (or re-import) run.py for a given solar size.  run.py reads
    its plant data at import time, driven by sys.argv, so argv has to be
    set first.  Same pattern as duals.py."""
    sys.argv = ["payoff.py", "lp", str(solar_size), "0", scenario]
    if "run" in sys.modules:
        del sys.modules["run"]
    import run
    return run


def compute_payoff(solar_size):
    """Return the 4x4 payoff table P (row k = minimise objective k alone)
    together with the ideal and nadir vectors."""
    run = reload_run(solar_size)
    P = []
    for k in range(len(OBJECTIVES)):
        wts = [0.0] * len(OBJECTIVES)
        wts[k] = 1.0
        _, costs = run.lp_solve(wts[0], wts[1], wts[2], wts[3])
        P.append(costs)
    P = np.array(P)
    # these must agree with run.payoff_table(), which is what the
    # normalised runs actually use
    ideal, nadir, _ = run.payoff_table()
    assert np.allclose(P.diagonal(), ideal)
    assert np.allclose(P.max(axis=0), nadir)
    return P, ideal, nadir


def to_long(results):
    """One row per (solar size, row of the payoff table), plus min, max
    and range rows, for the machine-readable CSV."""
    rows = []
    for s, (P, ideal, nadir) in results.items():
        for k, lab in enumerate(LABELS):
            rows.append([s, f"minimise {lab.lower()}", *P[k]])
        rows.append([s, "min (ideal)", *ideal])
        rows.append([s, "max (nadir estimate)", *nadir])
        rows.append([s, "range", *(nadir - ideal)])
    return pd.DataFrame(rows, columns=["solar_mw", "row", *OBJECTIVES])


def to_latex(results):
    """Full payoff table, one block per solar size, in raw units.  The
    diagonal (each objective's min) is in bold; the last row of each
    block is the max (nadir estimate)."""
    out = []
    out.append("% generated by src/payoff.py -- do not edit")
    out.append(r"\begin{table}")
    out.append(r"\caption{Single-objective optimisation and normalisation constants. "
               r"Each row gives all four objective values "
               r"at the solution that minimises one objective alone. "
               r"The diagonal, in bold, is each objective's minimum "
               r"(ideal) value. The ``Max'' row is the largest value "
               r"each objective takes when any one of the other "
               r"objectives is minimised alone, " 
               r"i.e.~its maximum (nadir) value. The normalisation range "
               r"is Max minus the bold minimum.}")
    out.append(r"\label{tab:payoff}")
    out.append(r"\begin{tabular}{rl" + "r" * len(OBJECTIVES) + "}")
    out.append(r"\toprule")
    out.append("Solar (MW) & Minimise alone & " + " & ".join(LABELS)
               + r" \\")
    for s, (P, _ideal, nadir) in results.items():
        out.append(r"\midrule")
        for k, lab in enumerate(LABELS):
            cells = []
            for j in range(len(OBJECTIVES)):
                v = f"{P[k, j]:.3e}"
                cells.append(rf"\textbf{{{v}}}" if j == k else v)
            first = str(s) if k == 0 else ""
            out.append(f"{first} & {lab} & " + " & ".join(cells) + r" \\")
        cells = [f"{v:.3e}" for v in nadir]
        out.append(r" & Max (nadir) & " + " & ".join(cells)
                   + r" \\")
    out.append(r"\bottomrule")
    out.append(r"\end{tabular}")
    out.append(r"\end{table}")
    return "\n".join(out) + "\n"


if __name__ == "__main__":
    results = {s: compute_payoff(s) for s in SOLAR_SIZES}

    os.makedirs(DERIVED, exist_ok=True)
    df = to_long(results)
    df.to_csv(os.path.join(DERIVED, "payoff_table.csv"), index=False)

    with open(os.path.join(TABDIR, "payoff_table.tex"), "w") as f:
        f.write(to_latex(results))

    pd.set_option("display.width", 200)
    pd.set_option("display.float_format", lambda v: f"{v:.3e}")
    print(df.to_string(index=False))
